using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace AstQuerying.Queries.Analyzers;

/// <summary>
///     Incremental source generator that emits query metadata for types marked with
///     <c>[QueryableEntity]</c>.
/// </summary>
[Generator]
public sealed class QueryableEntityGenerator : IIncrementalGenerator
{
    private const string QueryableEntityAttributeName = "AstQuerying.Queries.Metadata.Attributes.QueryableEntityAttribute";
    private const string DefaultSortAttributeName = "AstQuerying.Queries.Metadata.Attributes.DefaultSortAttribute";
    private const string DefaultFilterAttributeName = "AstQuerying.Queries.Metadata.Attributes.DefaultFilterAttribute";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var entities = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                QueryableEntityAttributeName,
                static (node, _) => node is TypeDeclarationSyntax { AttributeLists.Count: > 0 },
                static (ctx, ct) => GetEntityModel(ctx, ct))
            .Where(static model => model is not null)!;

        context.RegisterSourceOutput(entities, static (spc, model) => Emit(spc, model!));
    }

    private static EntityModel? GetEntityModel(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        if (context.TargetSymbol is not INamedTypeSymbol typeSymbol)
            return null;

        if (typeSymbol.TypeKind != TypeKind.Class && typeSymbol.TypeKind != TypeKind.Struct)
            return null;

        var properties = PropertyPathWalker.Walk(typeSymbol, cancellationToken);
        if (properties.Count == 0)
            return null;

        var defaultSortJson = GetDefaultSortJson(context);
        var defaultFilterJson = GetDefaultFilterJson(context);

        return new EntityModel(
            typeSymbol,
            properties,
            defaultSortJson,
            defaultFilterJson);
    }

    private static string? GetDefaultSortJson(GeneratorAttributeSyntaxContext context)
    {
        foreach (var attr in context.Attributes)
        {
            if (!string.Equals(attr.AttributeClass?.ToDisplayString(), DefaultSortAttributeName, StringComparison.Ordinal))
                continue;

            if (attr.ConstructorArguments.Length < 1)
                continue;

            return attr.ConstructorArguments[0].Value as string;
        }

        return null;
    }

    private static string? GetDefaultFilterJson(GeneratorAttributeSyntaxContext context)
    {
        foreach (var attr in context.Attributes)
        {
            if (!string.Equals(attr.AttributeClass?.ToDisplayString(), DefaultFilterAttributeName, StringComparison.Ordinal))
                continue;

            if (attr.ConstructorArguments.Length < 1)
                continue;

            return attr.ConstructorArguments[0].Value as string;
        }

        return null;
    }

    private static void Emit(SourceProductionContext context, EntityModel model)
    {
        var sb = new StringBuilder();
        var ns = model.TypeSymbol.ContainingNamespace.IsGlobalNamespace
            ? null
            : model.TypeSymbol.ContainingNamespace.ToDisplayString();
        var typeName = model.TypeSymbol.Name;
        var registrationClass = $"{typeName}QueryMetadataRegistration";

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Runtime.CompilerServices;");
        sb.AppendLine("using System.Text.Json;");
        sb.AppendLine("using AstQuerying.Queries.Filters.Dtos;");
        sb.AppendLine("using AstQuerying.Queries.Metadata;");
        sb.AppendLine("using AstQuerying.Queries.Metadata.ValueObjects;");
        sb.AppendLine("using AstQuerying.Queries.Sorting.Dtos;");

        if (ns is not null)
            sb.AppendLine($"namespace {ns};");
        else
            sb.AppendLine();

        sb.AppendLine($"file static class {registrationClass}");
        sb.AppendLine("{");
        sb.AppendLine("    [ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine($"        QueryMetadataRegistry.Register(typeof({typeName}), new EntityMetadata(");
        sb.AppendLine($"            typeof({typeName}),");
        sb.AppendLine("            [");

        for (var i = 0; i < model.Properties.Count; i++)
        {
            var prop = model.Properties[i];
            var leafType = PropertyPathWalker.GetTypeDisplayName(prop.LeafType);
            sb.AppendLine($"                new PropertyMetadata(\"{Escape(prop.Path)}\", typeof({leafType}), [");
            for (var j = 0; j < prop.Segments.Count; j++)
            {
                var seg = prop.Segments[j];
                var memberType = PropertyPathWalker.GetTypeDisplayName(seg.MemberType);
                var comma = j < prop.Segments.Count - 1 ? "," : "";
                sb.AppendLine(
                    $"                    new PathSegment(\"{Escape(seg.Name)}\", typeof({memberType}), {seg.IsCollection.ToString().ToLowerInvariant()}){comma}");
            }

            var propComma = i < model.Properties.Count - 1 ? "," : "";
            sb.AppendLine($"                ]){propComma}");
        }

        sb.AppendLine("            ],");

        if (model.DefaultSortJson is not null)
        {
            sb.AppendLine(
                $"            defaultSort: JsonSerializer.Deserialize<List<SortFieldDto>>(\"{Escape(model.DefaultSortJson)}\")");
        }
        else
        {
            sb.AppendLine("            defaultSort: null,");
        }

        if (model.DefaultFilterJson is not null)
        {
            sb.AppendLine(
                $"            defaultFilter: JsonSerializer.Deserialize<FilterClauseDto>(\"{Escape(model.DefaultFilterJson)}\")");
        }
        else
        {
            sb.AppendLine("            defaultFilter: null");
        }

        sb.AppendLine("        ));");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        var fileName = $"{typeName}.QueryMetadata.g.cs";
        context.AddSource(fileName, SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private sealed class EntityModel
    {
        public EntityModel(
            INamedTypeSymbol typeSymbol,
            IReadOnlyList<PropertyPathWalker.PropertyPathInfo> properties,
            string? defaultSortJson,
            string? defaultFilterJson)
        {
            TypeSymbol = typeSymbol;
            Properties = properties;
            DefaultSortJson = defaultSortJson;
            DefaultFilterJson = defaultFilterJson;
        }

        public INamedTypeSymbol TypeSymbol { get; }
        public IReadOnlyList<PropertyPathWalker.PropertyPathInfo> Properties { get; }
        public string? DefaultSortJson { get; }
        public string? DefaultFilterJson { get; }
    }
}
